import { emit, fail } from '../scripts/lib/emit.mjs';
import { delay } from '../scripts/lib/shell.mjs';
import { clearRateLimits } from './lib/clean.mjs';
import { newTraceparent, startApp } from './lib/harness.mjs';
import { fetchTrace } from './lib/trace-backend.mjs';

/**
 * One key opens two doors.
 *
 *   npm run demo:trace
 *
 * The `trace_id` in a line of the log is the `trace_id` of a span in the trace backend,
 * and both are the id that arrived in the `traceparent` header. That is the sentence the
 * whole lecture is about, and it is worth being precise about why it is not free: the
 * correlator in the log has to be **the active span's id**, taken from OpenTelemetry's
 * own context. A uuid generated by a middleware looks exactly the same in a log line,
 * appears in the same place, reads the same to a human — and matches nothing in any trace
 * and nothing in any header.
 *
 * Two requests, because they prove different halves:
 *
 * - one against a route that reaches the database, so the trace has a **nested** span and
 *   is a tree rather than a single rectangle;
 * - one against a route that answers 500, because OpenTelemetry leaves a span `Unset` for
 *   a 4xx — a refused request is the client's error — and only a server error produces
 *   the ERROR status.
 */

const SPAN_FLOOR = 2;

function requiredUrl(name) {
    const value = process.env[name];

    if (value === undefined || value.trim() === '') {
        throw new Error(
            `${name} is not set. This demo needs the stand: \`docker compose up -d --wait\`, ` +
                'then export the two addresses from the Grading section of README.md.',
        );
    }

    return value;
}

async function main() {
    await clearRateLimits();

    const otlpEndpoint = requiredUrl('OTEL_EXPORTER_OTLP_ENDPOINT');
    const traceApiUrl = requiredUrl('TRACE_API_URL');

    const app = await startApp({ OTEL_EXPORTER_OTLP_ENDPOINT: otlpEndpoint });

    try {
        // --- a request that reaches the database -------------------------------------
        const read = newTraceparent();

        await fetch(`${app.baseUrl}/products?limit=1`, {
            headers: { traceparent: read.header },
        });

        // --- a request that fails ------------------------------------------------------
        const broken = newTraceparent();

        const failing = await fetch(`${app.baseUrl}/demo/fail`, {
            headers: { traceparent: broken.header },
        });

        await Promise.all([app.waitForRequest(read.traceId), app.waitForRequest(broken.traceId)]);

        // A batch exporter sends on a timer. Without this the demo asks the backend for a
        // trace the process is still holding and concludes that nothing was recorded.
        await app.flushSpans();
        await delay(250);

        const trace = await fetchTrace(traceApiUrl, read.traceId);
        const brokenTrace = await fetchTrace(traceApiUrl, broken.traceId);

        const logged = app.records.filter(
            (record) => record.trace_id === read.traceId && record.layer === 'http.access',
        );
        const spanTraceIds = new Set(trace.spans.map((span) => span.traceId));

        emit('spans', trace.spans.length);
        emit('orphan-spans', trace.orphansExcluding(read.spanId));
        emit('trace-matches-header', spanTraceIds.has(read.traceId) ? 1 : 0);
        emit(
            'trace-matches-log',
            logged.length > 0 && spanTraceIds.has(logged[0].trace_id) ? 1 : 0,
        );
        emit('span-status-error', brokenTrace.hasErrorStatus ? 1 : 0);
        emit('failing-status', failing.status);
        emit('broken-spans', brokenTrace.spans.length);

        if (trace.spans.length < SPAN_FLOOR) {
            fail(
                `${trace.spans.length} spans: a trace with no nested span says a request ` +
                    'happened and nothing about where its time went.',
            );
        }

        if (trace.orphansExcluding(read.spanId) !== 0) {
            fail('a span points at a parent that is not in the trace.');
        }

        if (!spanTraceIds.has(read.traceId)) {
            fail(
                'the trace in the backend does not carry the id from the traceparent ' +
                    'header: the service started a trace of its own instead of continuing one.',
            );
        }

        if (logged.length === 0 || !spanTraceIds.has(logged[0].trace_id)) {
            fail(
                'the trace_id in the log is not the trace_id of the span: the correlator ' +
                    'is not the active span, and the log and the trace are two systems.',
            );
        }

        if (!brokenTrace.hasErrorStatus) {
            fail(`a ${failing.status} produced no span with status ERROR.`);
        }
    } finally {
        await app.stop();
    }
}

main().catch((error) => {
    console.error(`\ndemo:trace failed: ${error.message}\n`);
    process.exitCode = 2;
});
